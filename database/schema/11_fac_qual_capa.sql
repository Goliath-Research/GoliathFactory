-- GoliathFactory Phase 3 — CAPA (corrective / preventive action)
SET client_min_messages = warning;

CREATE TABLE IF NOT EXISTS fac_qual.capas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id integer NOT NULL REFERENCES fac_eng.sites (id) ON DELETE RESTRICT,
  capa_number text NOT NULL,
  title text NOT NULL,
  root_cause text,
  status text NOT NULL DEFAULT 'open',
  effectiveness_notes text,
  opened_at timestamptz NOT NULL DEFAULT now(),
  closed_at timestamptz,
  closed_by_user_id integer,
  UNIQUE (site_id, capa_number)
);

CREATE TABLE IF NOT EXISTS fac_qual.capa_source_ncrs (
  capa_id integer NOT NULL REFERENCES fac_qual.capas (id) ON DELETE CASCADE,
  ncr_id integer NOT NULL REFERENCES fac_qual.ncrs (id) ON DELETE RESTRICT,
  PRIMARY KEY (capa_id, ncr_id)
);

CREATE TABLE IF NOT EXISTS fac_qual.capa_actions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  capa_id integer NOT NULL REFERENCES fac_qual.capas (id) ON DELETE CASCADE,
  seq integer NOT NULL,
  description text NOT NULL,
  status text NOT NULL DEFAULT 'open',
  due_date date,
  completed_at timestamptz,
  UNIQUE (capa_id, seq)
);

CREATE OR REPLACE VIEW fac_qual.v_capa AS
SELECT
  c.id AS capa_id,
  c.site_id,
  c.capa_number,
  c.title,
  c.root_cause,
  c.status,
  c.effectiveness_notes,
  c.opened_at,
  c.closed_at,
  c.closed_by_user_id,
  (
    SELECT count(*)::integer
    FROM fac_qual.capa_source_ncrs cs
    WHERE cs.capa_id = c.id
  ) AS source_ncr_count,
  (
    SELECT count(*)::integer
    FROM fac_qual.capa_actions ca
    WHERE ca.capa_id = c.id AND ca.status <> 'complete'
  ) AS open_action_count
FROM fac_qual.capas c;

ALTER TABLE fac_qual.capas ENABLE ROW LEVEL SECURITY;
ALTER TABLE fac_qual.capa_source_ncrs ENABLE ROW LEVEL SECURITY;
ALTER TABLE fac_qual.capa_actions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS capas_site ON fac_qual.capas;
CREATE POLICY capas_site ON fac_qual.capas
  FOR ALL
  USING (
    fac_eng.fn_user_can_access_site(
      NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
      site_id
    )
  );

DROP POLICY IF EXISTS capa_source_ncrs_site ON fac_qual.capa_source_ncrs;
CREATE POLICY capa_source_ncrs_site ON fac_qual.capa_source_ncrs
  FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM fac_qual.capas c
      WHERE c.id = capa_id
        AND fac_eng.fn_user_can_access_site(
          NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
          c.site_id
        )
    )
  );

DROP POLICY IF EXISTS capa_actions_site ON fac_qual.capa_actions;
CREATE POLICY capa_actions_site ON fac_qual.capa_actions
  FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM fac_qual.capas c
      WHERE c.id = capa_id
        AND fac_eng.fn_user_can_access_site(
          NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
          c.site_id
        )
    )
  );

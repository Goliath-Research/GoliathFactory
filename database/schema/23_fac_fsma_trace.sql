-- GoliathFactory Phase 5 — FSMA 204 Critical Tracking Events (CTE) with Key Data Elements (KDE)
SET client_min_messages = warning;

CREATE TABLE IF NOT EXISTS fac_trace.fsma_cte_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id integer NOT NULL REFERENCES fac_eng.sites (id) ON DELETE RESTRICT,
  cte_type text NOT NULL,
  event_at timestamptz NOT NULL,
  lot_id integer REFERENCES fac_trace.lots (id) ON DELETE SET NULL,
  traceability_lot_code text NOT NULL,
  product_description text NOT NULL,
  quantity numeric(18, 6),
  quantity_uom text,
  location_code text,
  reference_doc_type text,
  reference_doc_number text,
  genealogy_link_id integer REFERENCES fac_trace.lot_links (id) ON DELETE SET NULL,
  recorded_by_user_id integer,
  recorded_at timestamptz NOT NULL DEFAULT now(),
  source text NOT NULL DEFAULT 'manual',
  CONSTRAINT fsma_cte_type_chk
    CHECK (cte_type IN ('receiving', 'transformation', 'creation', 'shipping'))
);

CREATE INDEX IF NOT EXISTS fsma_cte_events_site_event_idx
  ON fac_trace.fsma_cte_events (site_id, event_at DESC);

CREATE INDEX IF NOT EXISTS fsma_cte_events_lot_idx
  ON fac_trace.fsma_cte_events (lot_id, event_at DESC);

CREATE OR REPLACE VIEW fac_trace.v_fsma_cte AS
SELECT
  e.id AS cte_event_id,
  e.site_id,
  e.cte_type,
  e.event_at,
  e.lot_id,
  l.lot_number,
  e.traceability_lot_code,
  e.product_description,
  e.quantity,
  e.quantity_uom,
  e.location_code,
  e.reference_doc_type,
  e.reference_doc_number,
  e.genealogy_link_id,
  e.recorded_by_user_id,
  e.recorded_at,
  e.source
FROM fac_trace.fsma_cte_events e
LEFT JOIN fac_trace.lots l ON l.id = e.lot_id;

ALTER TABLE fac_trace.fsma_cte_events ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS fsma_cte_site ON fac_trace.fsma_cte_events;
CREATE POLICY fsma_cte_site ON fac_trace.fsma_cte_events
  FOR ALL
  USING (
    fac_eng.fn_user_can_access_site(
      NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
      site_id
    )
  );

CREATE TABLE IF NOT EXISTS fac_trace.fsma_traceability_exports (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id integer NOT NULL REFERENCES fac_eng.sites (id) ON DELETE RESTRICT,
  window_hours integer NOT NULL DEFAULT 24,
  row_count integer NOT NULL,
  csv_text text NOT NULL,
  generated_at timestamptz NOT NULL DEFAULT now(),
  generated_by_user_id integer
);

ALTER TABLE fac_trace.fsma_traceability_exports ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS fsma_exports_site ON fac_trace.fsma_traceability_exports;
CREATE POLICY fsma_exports_site ON fac_trace.fsma_traceability_exports
  FOR ALL
  USING (
    fac_eng.fn_user_can_access_site(
      NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
      site_id
    )
  );

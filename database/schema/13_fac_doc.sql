-- GoliathFactory Phase 3 — controlled documents (change workflow stubs)
SET client_min_messages = warning;

CREATE SCHEMA IF NOT EXISTS fac_doc;

CREATE TABLE IF NOT EXISTS fac_doc.documents (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id integer NOT NULL REFERENCES fac_eng.sites (id) ON DELETE RESTRICT,
  doc_number text NOT NULL,
  title text NOT NULL,
  doc_type text NOT NULL DEFAULT 'procedure',
  UNIQUE (site_id, doc_number)
);

CREATE TABLE IF NOT EXISTS fac_doc.document_revisions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id integer NOT NULL REFERENCES fac_doc.documents (id) ON DELETE CASCADE,
  revision text NOT NULL,
  status text NOT NULL DEFAULT 'draft',
  change_summary text,
  storage_ref text,
  effective_on date,
  submitted_at timestamptz,
  approved_at timestamptz,
  UNIQUE (document_id, revision)
);

CREATE TABLE IF NOT EXISTS fac_doc.document_approvals (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  revision_id integer NOT NULL REFERENCES fac_doc.document_revisions (id) ON DELETE CASCADE,
  approver_user_id integer,
  signature_meaning text,
  record_hash text,
  approved_at timestamptz NOT NULL DEFAULT now()
);

CREATE OR REPLACE VIEW fac_doc.v_document AS
SELECT
  d.id AS document_id,
  d.site_id,
  d.doc_number,
  d.title,
  d.doc_type,
  dr.id AS revision_id,
  dr.revision,
  dr.status,
  dr.change_summary,
  dr.effective_on,
  dr.submitted_at,
  dr.approved_at
FROM fac_doc.documents d
LEFT JOIN LATERAL (
  SELECT r.*
  FROM fac_doc.document_revisions r
  WHERE r.document_id = d.id
  ORDER BY r.id DESC
  LIMIT 1
) dr ON true;

ALTER TABLE fac_doc.documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE fac_doc.document_revisions ENABLE ROW LEVEL SECURITY;
ALTER TABLE fac_doc.document_approvals ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS documents_site ON fac_doc.documents;
CREATE POLICY documents_site ON fac_doc.documents
  FOR ALL
  USING (
    fac_eng.fn_user_can_access_site(
      NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
      site_id
    )
  );

DROP POLICY IF EXISTS document_revisions_site ON fac_doc.document_revisions;
CREATE POLICY document_revisions_site ON fac_doc.document_revisions
  FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM fac_doc.documents d
      WHERE d.id = document_id
        AND fac_eng.fn_user_can_access_site(
          NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
          d.site_id
        )
    )
  );

DROP POLICY IF EXISTS document_approvals_site ON fac_doc.document_approvals;
CREATE POLICY document_approvals_site ON fac_doc.document_approvals
  FOR ALL
  USING (
    EXISTS (
      SELECT 1
      FROM fac_doc.document_revisions dr
      JOIN fac_doc.documents d ON d.id = dr.document_id
      WHERE dr.id = revision_id
        AND fac_eng.fn_user_can_access_site(
          NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
          d.site_id
        )
    )
  );

-- GoliathFactory Phase 4 — maintenance assets, PM schedules, work orders, downtime
SET client_min_messages = warning;

CREATE SCHEMA IF NOT EXISTS fac_maint;

CREATE TABLE IF NOT EXISTS fac_maint.assets (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id integer NOT NULL REFERENCES fac_eng.sites (id) ON DELETE RESTRICT,
  asset_tag text NOT NULL,
  description text,
  work_center_id integer REFERENCES fac_eng.work_centers (id) ON DELETE SET NULL,
  status text NOT NULL DEFAULT 'active',
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (site_id, asset_tag)
);

CREATE TABLE IF NOT EXISTS fac_maint.pm_schedules (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asset_id integer NOT NULL REFERENCES fac_maint.assets (id) ON DELETE CASCADE,
  name text NOT NULL,
  interval_days integer NOT NULL CHECK (interval_days > 0),
  checklist_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  next_due_on date,
  last_completed_on date,
  active boolean NOT NULL DEFAULT true,
  UNIQUE (asset_id, name)
);

CREATE TABLE IF NOT EXISTS fac_maint.maintenance_orders (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asset_id integer NOT NULL REFERENCES fac_maint.assets (id) ON DELETE RESTRICT,
  pm_schedule_id integer REFERENCES fac_maint.pm_schedules (id) ON DELETE SET NULL,
  order_kind text NOT NULL DEFAULT 'pm',
  status text NOT NULL DEFAULT 'open',
  due_on date,
  assigned_user_id integer,
  opened_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  signer_user_id integer,
  signature_meaning text,
  record_hash text,
  CONSTRAINT maintenance_orders_status_chk
    CHECK (status IN ('open', 'in_progress', 'completed', 'cancelled'))
);

CREATE TABLE IF NOT EXISTS fac_maint.maintenance_checklist_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  maintenance_order_id integer NOT NULL REFERENCES fac_maint.maintenance_orders (id) ON DELETE CASCADE,
  item_code text NOT NULL,
  description text,
  completed boolean NOT NULL DEFAULT false,
  completed_at timestamptz,
  UNIQUE (maintenance_order_id, item_code)
);

CREATE TABLE IF NOT EXISTS fac_maint.downtime_events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id integer NOT NULL REFERENCES fac_eng.sites (id) ON DELETE RESTRICT,
  asset_id integer REFERENCES fac_maint.assets (id) ON DELETE SET NULL,
  work_center_id integer REFERENCES fac_eng.work_centers (id) ON DELETE SET NULL,
  started_at timestamptz NOT NULL,
  ended_at timestamptz,
  reason_code text NOT NULL,
  comments text,
  logged_by_user_id integer,
  recorded_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT downtime_asset_or_wc_chk
    CHECK (asset_id IS NOT NULL OR work_center_id IS NOT NULL)
);

CREATE OR REPLACE VIEW fac_maint.v_asset AS
SELECT
  a.id AS asset_id,
  a.site_id,
  a.asset_tag,
  a.description,
  a.work_center_id,
  wc.code AS work_center_code,
  ps.id AS pm_schedule_id,
  ps.name AS pm_schedule_name,
  ps.interval_days,
  ps.next_due_on,
  ps.last_completed_on,
  (
    SELECT COALESCE(SUM(
      EXTRACT(EPOCH FROM (COALESCE(d.ended_at, now()) - d.started_at)) / 3600.0
    ), 0)
    FROM fac_maint.downtime_events d
    WHERE d.asset_id = a.id
      AND d.started_at >= (CURRENT_DATE - interval '30 days')
  ) AS downtime_hours_30d,
  a.status
FROM fac_maint.assets a
LEFT JOIN fac_eng.work_centers wc ON wc.id = a.work_center_id
LEFT JOIN LATERAL (
  SELECT s.*
  FROM fac_maint.pm_schedules s
  WHERE s.asset_id = a.id AND s.active
  ORDER BY s.next_due_on NULLS LAST, s.id
  LIMIT 1
) ps ON true;

ALTER TABLE fac_maint.assets ENABLE ROW LEVEL SECURITY;
ALTER TABLE fac_maint.pm_schedules ENABLE ROW LEVEL SECURITY;
ALTER TABLE fac_maint.maintenance_orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE fac_maint.maintenance_checklist_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE fac_maint.downtime_events ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS assets_site ON fac_maint.assets;
CREATE POLICY assets_site ON fac_maint.assets
  FOR ALL
  USING (
    fac_eng.fn_user_can_access_site(
      NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
      site_id
    )
  );

DROP POLICY IF EXISTS pm_schedules_site ON fac_maint.pm_schedules;
CREATE POLICY pm_schedules_site ON fac_maint.pm_schedules
  FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM fac_maint.assets a
      WHERE a.id = asset_id
        AND fac_eng.fn_user_can_access_site(
          NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
          a.site_id
        )
    )
  );

DROP POLICY IF EXISTS maintenance_orders_site ON fac_maint.maintenance_orders;
CREATE POLICY maintenance_orders_site ON fac_maint.maintenance_orders
  FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM fac_maint.assets a
      WHERE a.id = asset_id
        AND fac_eng.fn_user_can_access_site(
          NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
          a.site_id
        )
    )
  );

DROP POLICY IF EXISTS maintenance_checklist_site ON fac_maint.maintenance_checklist_items;
CREATE POLICY maintenance_checklist_site ON fac_maint.maintenance_checklist_items
  FOR ALL
  USING (
    EXISTS (
      SELECT 1
      FROM fac_maint.maintenance_orders mo
      JOIN fac_maint.assets a ON a.id = mo.asset_id
      WHERE mo.id = maintenance_order_id
        AND fac_eng.fn_user_can_access_site(
          NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
          a.site_id
        )
    )
  );

DROP POLICY IF EXISTS downtime_site ON fac_maint.downtime_events;
CREATE POLICY downtime_site ON fac_maint.downtime_events
  FOR ALL
  USING (
    fac_eng.fn_user_can_access_site(
      NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
      site_id
    )
  );

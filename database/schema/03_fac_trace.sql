-- GoliathFactory Phase 1 — fac_trace (lots, genealogy links)
SET client_min_messages = warning;

CREATE SCHEMA IF NOT EXISTS fac_trace;

CREATE TABLE IF NOT EXISTS fac_trace.lots (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id integer NOT NULL REFERENCES fac_eng.sites (id) ON DELETE RESTRICT,
  lot_number text NOT NULL,
  kind text NOT NULL DEFAULT 'production',
  heat_number text,
  cert_ref text,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (site_id, lot_number)
);

ALTER TABLE fac_prod.work_orders
  DROP CONSTRAINT IF EXISTS work_orders_output_lot_fk;
ALTER TABLE fac_prod.work_orders
  ADD CONSTRAINT work_orders_output_lot_fk
  FOREIGN KEY (output_lot_id) REFERENCES fac_trace.lots (id);

CREATE TABLE IF NOT EXISTS fac_trace.lot_links (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_lot_id integer NOT NULL REFERENCES fac_trace.lots (id) ON DELETE CASCADE,
  child_lot_id integer NOT NULL REFERENCES fac_trace.lots (id) ON DELETE CASCADE,
  link_kind text NOT NULL DEFAULT 'consume',
  CHECK (parent_lot_id <> child_lot_id),
  UNIQUE (parent_lot_id, child_lot_id, link_kind)
);

CREATE OR REPLACE VIEW fac_trace.v_lot AS
SELECT
  l.id AS lot_id,
  l.site_id,
  l.lot_number,
  l.kind,
  l.heat_number,
  l.cert_ref,
  l.created_at
FROM fac_trace.lots l;

CREATE OR REPLACE FUNCTION fac_trace.fn_genealogy(
  p_lot_id integer,
  p_direction text DEFAULT 'forward'
)
RETURNS TABLE (
  lot_id integer,
  lot_number text,
  kind text,
  depth integer,
  direction text,
  link_kind text,
  related_lot_id integer,
  related_lot_number text
)
LANGUAGE plpgsql
STABLE
SET search_path = fac_trace, pg_temp
AS $$
BEGIN
  IF p_direction NOT IN ('forward', 'backward') THEN
    RAISE EXCEPTION 'direction must be forward or backward';
  END IF;

  IF p_direction = 'forward' THEN
    RETURN QUERY
    WITH RECURSIVE tree AS (
      SELECT
        l.id AS lot_id,
        l.lot_number,
        l.kind,
        0 AS depth,
        p_direction AS direction,
        NULL::text AS link_kind,
        NULL::integer AS related_lot_id,
        NULL::text AS related_lot_number
      FROM fac_trace.lots l
      WHERE l.id = p_lot_id
      UNION ALL
      SELECT
        child.id,
        child.lot_number,
        child.kind,
        tree.depth + 1,
        p_direction,
        ll.link_kind,
        tree.lot_id,
        tree.lot_number
      FROM tree
      JOIN fac_trace.lot_links ll ON ll.parent_lot_id = tree.lot_id
      JOIN fac_trace.lots child ON child.id = ll.child_lot_id
      WHERE tree.depth < 50
    )
    SELECT * FROM tree;
  ELSE
    RETURN QUERY
    WITH RECURSIVE tree AS (
      SELECT
        l.id AS lot_id,
        l.lot_number,
        l.kind,
        0 AS depth,
        p_direction AS direction,
        NULL::text AS link_kind,
        NULL::integer AS related_lot_id,
        NULL::text AS related_lot_number
      FROM fac_trace.lots l
      WHERE l.id = p_lot_id
      UNION ALL
      SELECT
        parent.id,
        parent.lot_number,
        parent.kind,
        tree.depth + 1,
        p_direction,
        ll.link_kind,
        tree.lot_id,
        tree.lot_number
      FROM tree
      JOIN fac_trace.lot_links ll ON ll.child_lot_id = tree.lot_id
      JOIN fac_trace.lots parent ON parent.id = ll.parent_lot_id
      WHERE tree.depth < 50
    )
    SELECT * FROM tree;
  END IF;
END;
$$;

ALTER TABLE fac_trace.lots ENABLE ROW LEVEL SECURITY;
ALTER TABLE fac_trace.lot_links ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS lots_site ON fac_trace.lots;
CREATE POLICY lots_site ON fac_trace.lots
  FOR ALL
  USING (
    fac_eng.fn_user_can_access_site(
      NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
      site_id
    )
  );

DROP POLICY IF EXISTS lot_links_site ON fac_trace.lot_links;
CREATE POLICY lot_links_site ON fac_trace.lot_links
  FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM fac_trace.lots l
      WHERE l.id = parent_lot_id
        AND fac_eng.fn_user_can_access_site(
          NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
          l.site_id
        )
    )
    AND EXISTS (
      SELECT 1 FROM fac_trace.lots l
      WHERE l.id = child_lot_id
        AND fac_eng.fn_user_can_access_site(
          NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
          l.site_id
        )
    )
  );

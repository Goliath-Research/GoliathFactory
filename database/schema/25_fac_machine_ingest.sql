-- GoliathFactory Phase 5 — machine monitoring observations (MTConnect / OPC UA stubs)
SET client_min_messages = warning;

CREATE TABLE IF NOT EXISTS fac_maint.machine_observations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id integer NOT NULL REFERENCES fac_eng.sites (id) ON DELETE RESTRICT,
  asset_id integer REFERENCES fac_maint.assets (id) ON DELETE SET NULL,
  source_protocol text NOT NULL,
  observed_at timestamptz NOT NULL,
  availability text,
  execution_state text,
  raw_payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  incomplete_edges text[] NOT NULL DEFAULT '{}'::text[],
  downtime_event_id integer REFERENCES fac_maint.downtime_events (id) ON DELETE SET NULL,
  ingested_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT machine_obs_protocol_chk
    CHECK (source_protocol IN ('mtconnect', 'opcua'))
);

CREATE INDEX IF NOT EXISTS machine_observations_asset_idx
  ON fac_maint.machine_observations (asset_id, observed_at DESC);

ALTER TABLE fac_maint.machine_observations ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS machine_obs_site ON fac_maint.machine_observations;
CREATE POLICY machine_obs_site ON fac_maint.machine_observations
  FOR ALL
  USING (
    fac_eng.fn_user_can_access_site(
      NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
      site_id
    )
  );

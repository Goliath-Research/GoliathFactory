-- GoliathFactory Phase 3 — gauge calibration
SET client_min_messages = warning;

CREATE SCHEMA IF NOT EXISTS fac_gauge;

CREATE TABLE IF NOT EXISTS fac_gauge.gauges (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id integer NOT NULL REFERENCES fac_eng.sites (id) ON DELETE RESTRICT,
  gauge_tag text NOT NULL,
  gauge_type text NOT NULL,
  location text,
  cal_interval_days integer NOT NULL DEFAULT 365,
  last_calibrated_on date,
  next_cal_due_on date,
  locked_out boolean NOT NULL DEFAULT false,
  status text NOT NULL DEFAULT 'active',
  UNIQUE (site_id, gauge_tag)
);

CREATE TABLE IF NOT EXISTS fac_gauge.calibrations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gauge_id integer NOT NULL REFERENCES fac_gauge.gauges (id) ON DELETE CASCADE,
  performed_on date NOT NULL,
  next_due_on date NOT NULL,
  result text NOT NULL DEFAULT 'pass',
  cert_storage_ref text,
  performed_by_user_id integer,
  recorded_at timestamptz NOT NULL DEFAULT now()
);

CREATE OR REPLACE VIEW fac_gauge.v_gauge AS
SELECT
  g.id AS gauge_id,
  g.site_id,
  g.gauge_tag,
  g.gauge_type,
  g.location,
  g.cal_interval_days,
  g.last_calibrated_on,
  g.next_cal_due_on,
  g.locked_out
    OR (g.next_cal_due_on IS NOT NULL AND g.next_cal_due_on < CURRENT_DATE)
    OR g.status <> 'active' AS locked_out,
  g.status
FROM fac_gauge.gauges g;

ALTER TABLE fac_gauge.gauges ENABLE ROW LEVEL SECURITY;
ALTER TABLE fac_gauge.calibrations ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS gauges_site ON fac_gauge.gauges;
CREATE POLICY gauges_site ON fac_gauge.gauges
  FOR ALL
  USING (
    fac_eng.fn_user_can_access_site(
      NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
      site_id
    )
  );

DROP POLICY IF EXISTS calibrations_site ON fac_gauge.calibrations;
CREATE POLICY calibrations_site ON fac_gauge.calibrations
  FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM fac_gauge.gauges g
      WHERE g.id = gauge_id
        AND fac_eng.fn_user_can_access_site(
          NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
          g.site_id
        )
    )
  );

-- GoliathFactory Phase 3 — certificate of conformance records
SET client_min_messages = warning;

CREATE TABLE IF NOT EXISTS fac_trace.certificates_of_conformance (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id integer NOT NULL REFERENCES fac_eng.sites (id) ON DELETE RESTRICT,
  lot_id integer NOT NULL REFERENCES fac_trace.lots (id) ON DELETE RESTRICT,
  coc_number text NOT NULL,
  document_json jsonb NOT NULL,
  record_hash text NOT NULL,
  generated_at timestamptz NOT NULL DEFAULT now(),
  generated_by_user_id integer,
  UNIQUE (site_id, coc_number)
);

CREATE INDEX IF NOT EXISTS certificates_of_conformance_lot_idx
  ON fac_trace.certificates_of_conformance (lot_id, generated_at DESC);

ALTER TABLE fac_trace.certificates_of_conformance ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS certificates_of_conformance_site ON fac_trace.certificates_of_conformance;
CREATE POLICY certificates_of_conformance_site ON fac_trace.certificates_of_conformance
  FOR ALL
  USING (
    fac_eng.fn_user_can_access_site(
      NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
      site_id
    )
  );

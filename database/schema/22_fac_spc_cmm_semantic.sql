-- GoliathFactory Phase 4 — SPC snapshots (worker-written) and CMM import batches
SET client_min_messages = warning;

CREATE TABLE IF NOT EXISTS fac_qual.spc_chart_points (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  characteristic_id integer NOT NULL REFERENCES fac_qual.inspection_characteristics (id) ON DELETE CASCADE,
  chart_type text NOT NULL,
  point_index integer NOT NULL,
  subgroup_label text,
  primary_value numeric(18, 6) NOT NULL,
  secondary_value numeric(18, 6),
  center_line numeric(18, 6),
  ucl numeric(18, 6),
  lcl numeric(18, 6),
  rule_violations text,
  computed_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (characteristic_id, chart_type, point_index)
);

CREATE OR REPLACE VIEW fac_qual.v_spc_series AS
SELECT
  p.characteristic_id,
  ic.characteristic_code,
  ic.description AS characteristic_description,
  ip.site_id,
  p.chart_type,
  p.point_index,
  p.subgroup_label,
  p.primary_value,
  p.secondary_value,
  p.center_line,
  p.ucl,
  p.lcl,
  p.rule_violations,
  p.computed_at
FROM fac_qual.spc_chart_points p
JOIN fac_qual.inspection_characteristics ic ON ic.id = p.characteristic_id
JOIN fac_qual.inspection_plans ip ON ip.id = ic.inspection_plan_id;

CREATE TABLE IF NOT EXISTS fac_qual.cmm_import_batches (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id integer NOT NULL REFERENCES fac_eng.sites (id) ON DELETE RESTRICT,
  source_filename text NOT NULL,
  format text NOT NULL DEFAULT 'csv',
  status text NOT NULL DEFAULT 'pending',
  rows_parsed integer NOT NULL DEFAULT 0,
  rows_inserted integer NOT NULL DEFAULT 0,
  error_summary text,
  uploaded_by_user_id integer,
  uploaded_at timestamptz NOT NULL DEFAULT now(),
  processed_at timestamptz,
  CONSTRAINT cmm_import_batches_status_chk
    CHECK (status IN ('pending', 'processing', 'completed', 'failed'))
);

CREATE OR REPLACE FUNCTION fac_qual.sp_register_cmm_upload(
  p_user_id integer,
  p_site_id integer,
  p_source_filename text,
  p_format text DEFAULT 'csv',
  p_storage_ref text DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = fac_qual, fac_eng, fac_wf, portal, pg_temp
AS $$
DECLARE
  v_batch_id bigint;
BEGIN
  IF p_user_id IS NULL THEN
    PERFORM portal.fn_semantic_raise('GS401', 'user required');
  END IF;
  IF p_site_id IS NULL OR NOT fac_eng.fn_user_can_access_site(p_user_id, p_site_id) THEN
    PERFORM portal.fn_semantic_raise('GS403', 'site scope denied');
  END IF;
  PERFORM set_config('goliath.mfg.user_id', p_user_id::text, true);

  INSERT INTO fac_qual.cmm_import_batches (
    site_id,
    source_filename,
    format,
    status,
    uploaded_by_user_id
  )
  VALUES (
    p_site_id,
    p_source_filename,
    COALESCE(p_format, 'csv'),
    'pending',
    p_user_id
  )
  RETURNING id INTO v_batch_id;

  PERFORM fac_wf.sp_enqueue_processing_task(
    'mfg.cmm.import_file',
    jsonb_build_object(
      'batch_id', v_batch_id,
      'site_id', p_site_id,
      'source_filename', p_source_filename,
      'format', COALESCE(p_format, 'csv'),
      'storage_ref', p_storage_ref
    ),
    'mfg.cmm',
    'cmm_upload_registered',
    'cmm:batch:' || v_batch_id::text
  );

  RETURN v_batch_id;
END;
$$;

CREATE OR REPLACE FUNCTION fac_qual.sp_enqueue_spc_backlog()
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = fac_qual, fac_wf, pg_temp
AS $$
DECLARE
  v_char record;
  v_count integer := 0;
BEGIN
  FOR v_char IN
    SELECT DISTINCT ic.id AS characteristic_id, ip.site_id
    FROM fac_qual.inspection_characteristics ic
    JOIN fac_qual.inspection_plans ip ON ip.id = ic.inspection_plan_id
    WHERE EXISTS (
      SELECT 1 FROM fac_qual.inspection_results ir
      WHERE ir.characteristic_id = ic.id
        AND ir.measured_value IS NOT NULL
    )
    ORDER BY ic.id
    LIMIT 200
  LOOP
    PERFORM fac_wf.sp_enqueue_processing_task(
      'mfg.spc.summarize',
      jsonb_build_object(
        'characteristic_id', v_char.characteristic_id,
        'site_id', v_char.site_id
      ),
      'mfg.spc',
      'nightly_spc_backlog',
      'spc:char:' || v_char.characteristic_id::text || ':' || gen_random_uuid()::text
    );
    v_count := v_count + 1;
  END LOOP;
  RETURN v_count;
END;
$$;

CREATE OR REPLACE FUNCTION fac_qual.fn_semantic_spc_series(
  p_user_id integer,
  p_params jsonb,
  p_limit integer
)
RETURNS TABLE (
  characteristic_id integer,
  characteristic_code text,
  site_id integer,
  chart_type text,
  point_index integer,
  subgroup_label text,
  primary_value numeric,
  secondary_value numeric,
  center_line numeric,
  ucl numeric,
  lcl numeric,
  rule_violations text
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = fac_qual, fac_eng, portal, pg_temp
AS $$
DECLARE
  v_characteristic_id integer;
  v_chart_type text;
  v_site_id integer;
  v_lim integer;
BEGIN
  IF p_user_id IS NULL THEN
    RETURN;
  END IF;
  v_characteristic_id := (p_params->>'characteristic_id')::integer;
  v_chart_type := COALESCE(NULLIF(p_params->>'chart_type', ''), 'xbar_r');
  IF v_characteristic_id IS NULL THEN
    PERFORM portal.fn_semantic_raise('GS501', 'characteristic_id is required');
  END IF;
  SELECT ip.site_id INTO v_site_id
  FROM fac_qual.inspection_characteristics ic
  JOIN fac_qual.inspection_plans ip ON ip.id = ic.inspection_plan_id
  WHERE ic.id = v_characteristic_id;
  IF v_site_id IS NULL OR NOT fac_eng.fn_user_can_access_site(p_user_id, v_site_id) THEN
    PERFORM portal.fn_semantic_raise('GS403', 'characteristic scope denied');
  END IF;
  v_lim := GREATEST(0, COALESCE(p_limit, 500));
  RETURN QUERY
  SELECT
    v.characteristic_id,
    v.characteristic_code,
    v.site_id,
    v.chart_type,
    v.point_index,
    v.subgroup_label,
    v.primary_value,
    v.secondary_value,
    v.center_line,
    v.ucl,
    v.lcl,
    v.rule_violations
  FROM fac_qual.v_spc_series v
  WHERE v.characteristic_id = v_characteristic_id
    AND v.chart_type = v_chart_type
  ORDER BY v.point_index
  LIMIT v_lim;
END;
$$;

CREATE OR REPLACE FUNCTION fac_maint.fn_semantic_asset_pm_due(
  p_user_id integer,
  p_params jsonb,
  p_limit integer
)
RETURNS TABLE (
  asset_id integer,
  site_id integer,
  asset_tag text,
  description text,
  work_center_code text,
  pm_schedule_name text,
  next_due_on date,
  interval_days integer,
  downtime_hours_30d numeric,
  status text
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = fac_maint, fac_eng, portal, pg_temp
AS $$
DECLARE
  v_site_id integer;
  v_within_days integer;
  v_lim integer;
BEGIN
  IF p_user_id IS NULL THEN
    RETURN;
  END IF;
  v_site_id := (p_params->>'site_id')::integer;
  IF v_site_id IS NULL THEN
    PERFORM portal.fn_semantic_raise('GS501', 'site_id is required');
  END IF;
  IF NOT fac_eng.fn_user_can_access_site(p_user_id, v_site_id) THEN
    PERFORM portal.fn_semantic_raise('GS403', 'site scope denied');
  END IF;
  v_within_days := COALESCE((p_params->>'within_days')::integer, 30);
  v_lim := GREATEST(0, COALESCE(p_limit, 500));
  RETURN QUERY
  SELECT
    v.asset_id,
    v.site_id,
    v.asset_tag,
    v.description,
    v.work_center_code,
    v.pm_schedule_name,
    v.next_due_on,
    v.interval_days,
    v.downtime_hours_30d,
    v.status
  FROM fac_maint.v_asset v
  WHERE v.site_id = v_site_id
    AND v.next_due_on IS NOT NULL
    AND v.next_due_on <= (CURRENT_DATE + v_within_days)
  ORDER BY v.next_due_on, v.asset_tag
  LIMIT v_lim;
END;
$$;

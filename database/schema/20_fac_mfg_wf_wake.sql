-- GoliathFactory Phase 4 — domain task backlog + Postgres NOTIFY wakes (dual activation)
SET client_min_messages = warning;

CREATE SCHEMA IF NOT EXISTS fac_wf;

CREATE TABLE IF NOT EXISTS fac_wf.processing_tasks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action_name text NOT NULL,
  input_json jsonb NOT NULL DEFAULT '{}'::jsonb,
  capability text NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  wake_id text,
  created_at timestamptz NOT NULL DEFAULT now(),
  claimed_at timestamptz,
  completed_at timestamptz,
  CONSTRAINT processing_tasks_status_chk
    CHECK (status IN ('pending', 'claimed', 'completed', 'failed'))
);

CREATE INDEX IF NOT EXISTS processing_tasks_pending_idx
  ON fac_wf.processing_tasks (capability, status, created_at)
  WHERE status = 'pending';

CREATE OR REPLACE FUNCTION fac_wf.fn_capability_pg_notify_channel(p_capability text)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT
    'gw1_'
    || replace(
      regexp_replace(
        'capability.' || trim(p_capability),
        '[^a-zA-Z0-9._-]+',
        '_',
        'g'
      ),
      '.',
      '_'
    );
$$;

CREATE OR REPLACE FUNCTION fac_wf.sp_publish_capability_wake(
  p_capability text,
  p_wake_id text,
  p_reason text DEFAULT 'mfg_domain_task',
  p_event_id bigint DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = fac_wf, pg_temp
AS $$
DECLARE
  v_channel text;
  v_payload text;
BEGIN
  IF p_capability IS NULL OR btrim(p_capability) = '' THEN
    RETURN;
  END IF;
  IF p_wake_id IS NULL OR btrim(p_wake_id) = '' THEN
    p_wake_id := 'mfg:' || gen_random_uuid()::text;
  END IF;
  v_channel := fac_wf.fn_capability_pg_notify_channel(p_capability);
  v_payload := json_build_object(
    'wake_id', p_wake_id,
    'reason', COALESCE(p_reason, 'mfg_domain_task'),
    'capability', p_capability,
    'event_id', p_event_id,
    'occurred_at_utc', to_char(timezone('UTC', now()), 'YYYY-MM-DD"T"HH24:MI:SS"Z"')
  )::text;
  PERFORM pg_notify(v_channel, v_payload);
END;
$$;

CREATE OR REPLACE FUNCTION fac_wf.sp_enqueue_processing_task(
  p_action_name text,
  p_input_json jsonb,
  p_capability text,
  p_wake_reason text DEFAULT NULL,
  p_wake_id text DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = fac_wf, pg_temp
AS $$
DECLARE
  v_task_id bigint;
  v_wake_id text;
BEGIN
  v_wake_id := COALESCE(
    p_wake_id,
    'task:' || replace(p_action_name, '.', '_') || ':' || gen_random_uuid()::text
  );
  INSERT INTO fac_wf.processing_tasks (
    action_name,
    input_json,
    capability,
    wake_id
  )
  VALUES (
    p_action_name,
    COALESCE(p_input_json, '{}'::jsonb),
    p_capability,
    v_wake_id
  )
  RETURNING id INTO v_task_id;

  PERFORM fac_wf.sp_publish_capability_wake(
    p_capability,
    v_wake_id,
    COALESCE(p_wake_reason, p_action_name),
    v_task_id
  );
  RETURN v_task_id;
END;
$$;

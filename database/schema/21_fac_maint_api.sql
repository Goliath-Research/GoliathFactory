-- GoliathFactory Phase 4 — maintenance writes, PM backlog, downtime
SET client_min_messages = warning;

CREATE TABLE IF NOT EXISTS fac_maint.pm_scan_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id integer NOT NULL REFERENCES fac_eng.sites (id) ON DELETE CASCADE,
  scanned_at timestamptz NOT NULL DEFAULT now(),
  due_asset_count integer NOT NULL DEFAULT 0,
  detail_json jsonb
);

CREATE OR REPLACE FUNCTION fac_maint.sp_wake_pm_scan_for_site(
  p_site_id integer,
  p_reason text DEFAULT 'pm_data_updated'
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = fac_maint, fac_wf, pg_temp
AS $$
BEGIN
  IF p_site_id IS NULL THEN
    RETURN NULL;
  END IF;
  RETURN fac_wf.sp_enqueue_processing_task(
    'mfg.maint.pm_due_scan',
    jsonb_build_object('site_id', p_site_id),
    'mfg.maint',
    COALESCE(p_reason, 'pm_data_updated'),
    'pm:site:' || p_site_id::text || ':' || gen_random_uuid()::text
  );
END;
$$;

CREATE OR REPLACE FUNCTION fac_maint.sp_enqueue_pm_due_backlog(
  p_within_days integer DEFAULT 7
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = fac_maint, fac_eng, fac_wf, pg_temp
AS $$
DECLARE
  v_site record;
  v_count integer := 0;
BEGIN
  FOR v_site IN
    SELECT DISTINCT a.site_id
    FROM fac_maint.assets a
    JOIN fac_maint.pm_schedules ps ON ps.asset_id = a.id AND ps.active
    WHERE ps.next_due_on IS NOT NULL
      AND ps.next_due_on <= (CURRENT_DATE + COALESCE(p_within_days, 7))
    ORDER BY a.site_id
    LIMIT 500
  LOOP
    PERFORM fac_maint.sp_wake_pm_scan_for_site(v_site.site_id, 'daily_pm_backlog');
    v_count := v_count + 1;
  END LOOP;
  RETURN v_count;
END;
$$;

CREATE OR REPLACE FUNCTION fac_maint.sp_open_pm_order(
  p_user_id integer,
  p_asset_id integer,
  p_pm_schedule_id integer DEFAULT NULL
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = fac_maint, fac_eng, portal, pg_temp
AS $$
DECLARE
  v_site_id integer;
  v_schedule_id integer;
  v_order_id integer;
  v_item jsonb;
BEGIN
  IF p_user_id IS NULL THEN
    PERFORM portal.fn_semantic_raise('GS401', 'user required');
  END IF;
  SELECT a.site_id INTO v_site_id FROM fac_maint.assets a WHERE a.id = p_asset_id;
  IF v_site_id IS NULL OR NOT fac_eng.fn_user_can_access_site(p_user_id, v_site_id) THEN
    PERFORM portal.fn_semantic_raise('GS403', 'asset scope denied');
  END IF;
  PERFORM set_config('goliath.mfg.user_id', p_user_id::text, true);

  IF p_pm_schedule_id IS NOT NULL THEN
    SELECT ps.id INTO v_schedule_id
    FROM fac_maint.pm_schedules ps
    WHERE ps.id = p_pm_schedule_id
      AND ps.asset_id = p_asset_id
      AND ps.active;
    IF v_schedule_id IS NULL THEN
      PERFORM portal.fn_semantic_raise('GS422', 'pm schedule not found for asset');
    END IF;
  ELSE
    SELECT ps.id INTO v_schedule_id
    FROM fac_maint.pm_schedules ps
    WHERE ps.asset_id = p_asset_id AND ps.active
    ORDER BY ps.next_due_on NULLS LAST, ps.id
    LIMIT 1;
  END IF;

  INSERT INTO fac_maint.maintenance_orders (asset_id, pm_schedule_id, order_kind, status, due_on)
  SELECT
    p_asset_id,
    v_schedule_id,
    'pm',
    'open',
    ps.next_due_on
  FROM fac_maint.pm_schedules ps
  WHERE ps.id = v_schedule_id
  RETURNING id INTO v_order_id;

  IF v_order_id IS NULL THEN
    INSERT INTO fac_maint.maintenance_orders (asset_id, order_kind, status)
    VALUES (p_asset_id, 'pm', 'open')
    RETURNING id INTO v_order_id;
  END IF;

  IF v_schedule_id IS NOT NULL THEN
    FOR v_item IN
      SELECT jsonb_array_elements(ps.checklist_json)
      FROM fac_maint.pm_schedules ps
      WHERE ps.id = v_schedule_id
    LOOP
      INSERT INTO fac_maint.maintenance_checklist_items (
        maintenance_order_id,
        item_code,
        description
      )
      VALUES (
        v_order_id,
        COALESCE(v_item->>'code', v_item->>'item_code', 'item'),
        v_item->>'description'
      )
      ON CONFLICT (maintenance_order_id, item_code) DO NOTHING;
    END LOOP;
  END IF;

  RETURN v_order_id;
END;
$$;

CREATE OR REPLACE FUNCTION fac_maint.sp_pm_complete(
  p_user_id integer,
  p_maintenance_order_id integer,
  p_signature_meaning text,
  p_record_hash text,
  p_checklist_json jsonb DEFAULT NULL
)
RETURNS date
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = fac_maint, fac_eng, fac_audit, portal, pg_temp
AS $$
DECLARE
  v_site_id integer;
  v_asset_id integer;
  v_schedule_id integer;
  v_status text;
  v_interval integer;
  v_next date := CURRENT_DATE;
  v_item record;
BEGIN
  IF p_user_id IS NULL THEN
    PERFORM portal.fn_semantic_raise('GS401', 'user required');
  END IF;
  IF p_signature_meaning IS NULL OR btrim(p_signature_meaning) = '' THEN
    PERFORM portal.fn_semantic_raise('GS422', 'signature_meaning required');
  END IF;
  IF p_record_hash IS NULL OR btrim(p_record_hash) = '' THEN
    PERFORM portal.fn_semantic_raise('GS422', 'record_hash required');
  END IF;

  SELECT a.site_id, mo.asset_id, mo.pm_schedule_id, mo.status
  INTO v_site_id, v_asset_id, v_schedule_id, v_status
  FROM fac_maint.maintenance_orders mo
  JOIN fac_maint.assets a ON a.id = mo.asset_id
  WHERE mo.id = p_maintenance_order_id;

  IF v_site_id IS NULL OR NOT fac_eng.fn_user_can_access_site(p_user_id, v_site_id) THEN
    PERFORM portal.fn_semantic_raise('GS403', 'maintenance order scope denied');
  END IF;
  IF v_status NOT IN ('open', 'in_progress') THEN
    PERFORM portal.fn_semantic_raise('GS409', 'maintenance order cannot be completed from current status');
  END IF;
  PERFORM set_config('goliath.mfg.user_id', p_user_id::text, true);

  IF p_checklist_json IS NOT NULL THEN
    FOR v_item IN
      SELECT key AS item_code, value::text AS completed
      FROM jsonb_each(p_checklist_json)
    LOOP
      UPDATE fac_maint.maintenance_checklist_items ci
      SET
        completed = (lower(v_item.completed) IN ('true', '1', 'yes')),
        completed_at = CASE
          WHEN lower(v_item.completed) IN ('true', '1', 'yes') THEN now()
          ELSE completed_at
        END
      WHERE ci.maintenance_order_id = p_maintenance_order_id
        AND ci.item_code = v_item.item_code;
    END LOOP;
  END IF;

  UPDATE fac_maint.maintenance_orders
  SET
    status = 'completed',
    completed_at = now(),
    signer_user_id = p_user_id,
    signature_meaning = p_signature_meaning,
    record_hash = p_record_hash
  WHERE id = p_maintenance_order_id;

  IF v_schedule_id IS NOT NULL THEN
    SELECT ps.interval_days INTO v_interval
    FROM fac_maint.pm_schedules ps
    WHERE ps.id = v_schedule_id;
    v_next := CURRENT_DATE + COALESCE(v_interval, 30);
    UPDATE fac_maint.pm_schedules
    SET last_completed_on = CURRENT_DATE, next_due_on = v_next
    WHERE id = v_schedule_id;
  END IF;

  PERFORM fac_audit.sp_append(
    v_site_id,
    'maintenance_order',
    p_maintenance_order_id,
    'mfg.asset.pm_complete',
    p_user_id,
    p_signature_meaning,
    p_record_hash,
    jsonb_build_object('asset_id', v_asset_id, 'pm_schedule_id', v_schedule_id)
  );

  PERFORM fac_maint.sp_wake_pm_scan_for_site(v_site_id, 'pm_completed');

  RETURN v_next;
END;
$$;

CREATE OR REPLACE FUNCTION fac_maint.sp_log_downtime(
  p_user_id integer,
  p_site_id integer,
  p_asset_id integer,
  p_work_center_id integer,
  p_started_at timestamptz,
  p_ended_at timestamptz,
  p_reason_code text,
  p_comments text DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = fac_maint, fac_eng, fac_audit, portal, pg_temp
AS $$
DECLARE
  v_id bigint;
  v_asset_site_id integer;
  v_wc_site_id integer;
BEGIN
  IF p_user_id IS NULL THEN
    PERFORM portal.fn_semantic_raise('GS401', 'user required');
  END IF;
  IF p_site_id IS NULL OR NOT fac_eng.fn_user_can_access_site(p_user_id, p_site_id) THEN
    PERFORM portal.fn_semantic_raise('GS403', 'site scope denied');
  END IF;
  IF p_asset_id IS NULL AND p_work_center_id IS NULL THEN
    PERFORM portal.fn_semantic_raise('GS422', 'asset_id or work_center_id required');
  END IF;
  IF p_asset_id IS NOT NULL THEN
    SELECT a.site_id INTO v_asset_site_id
    FROM fac_maint.assets a
    WHERE a.id = p_asset_id;
    IF v_asset_site_id IS NULL OR v_asset_site_id <> p_site_id THEN
      PERFORM portal.fn_semantic_raise('GS422', 'asset not at site');
    END IF;
  END IF;
  IF p_work_center_id IS NOT NULL THEN
    SELECT wc.site_id INTO v_wc_site_id
    FROM fac_eng.work_centers wc
    WHERE wc.id = p_work_center_id;
    IF v_wc_site_id IS NULL OR v_wc_site_id <> p_site_id THEN
      PERFORM portal.fn_semantic_raise('GS422', 'work center not at site');
    END IF;
  END IF;
  PERFORM set_config('goliath.mfg.user_id', p_user_id::text, true);

  INSERT INTO fac_maint.downtime_events (
    site_id,
    asset_id,
    work_center_id,
    started_at,
    ended_at,
    reason_code,
    comments,
    logged_by_user_id
  )
  VALUES (
    p_site_id,
    p_asset_id,
    p_work_center_id,
    p_started_at,
    p_ended_at,
    p_reason_code,
    p_comments,
    p_user_id
  )
  RETURNING id INTO v_id;

  PERFORM fac_audit.sp_append(
    p_site_id,
    'downtime_event',
    v_id::integer,
    'mfg.downtime.log',
    p_user_id,
    NULL,
    NULL,
    jsonb_build_object(
      'asset_id', p_asset_id,
      'work_center_id', p_work_center_id,
      'reason_code', p_reason_code
    )
  );

  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION fac_maint.sp_record_pm_scan_result(
  p_site_id integer,
  p_due_asset_count integer,
  p_detail_json jsonb DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = fac_maint, pg_temp
AS $$
DECLARE
  v_id bigint;
BEGIN
  INSERT INTO fac_maint.pm_scan_runs (site_id, due_asset_count, detail_json)
  VALUES (p_site_id, COALESCE(p_due_asset_count, 0), p_detail_json)
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

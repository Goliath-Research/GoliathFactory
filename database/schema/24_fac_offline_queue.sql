-- GoliathFactory Phase 5 — offline tablet outbox (idempotent sync)
SET client_min_messages = warning;

CREATE TABLE IF NOT EXISTS fac_prod.offline_outbox (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id integer NOT NULL REFERENCES fac_eng.sites (id) ON DELETE RESTRICT,
  client_device_id text NOT NULL,
  idempotency_key text NOT NULL,
  action_name text NOT NULL,
  payload_json jsonb NOT NULL,
  captured_at timestamptz NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  synced_at timestamptz,
  server_result_json jsonb,
  conflict_reason text,
  CONSTRAINT offline_outbox_status_chk
    CHECK (status IN ('pending', 'synced', 'conflict', 'rejected')),
  UNIQUE (site_id, client_device_id, idempotency_key)
);

CREATE INDEX IF NOT EXISTS offline_outbox_pending_idx
  ON fac_prod.offline_outbox (site_id, client_device_id, status, captured_at);

ALTER TABLE fac_prod.offline_outbox ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS offline_outbox_site ON fac_prod.offline_outbox;
CREATE POLICY offline_outbox_site ON fac_prod.offline_outbox
  FOR ALL
  USING (
    fac_eng.fn_user_can_access_site(
      NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
      site_id
    )
  );

-- GoliathFactory Phase 2 — fac_audit (domain audit log; e-sign fields on domain rows)
SET client_min_messages = warning;

CREATE SCHEMA IF NOT EXISTS fac_audit;

CREATE TABLE IF NOT EXISTS fac_audit.audit_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id integer REFERENCES fac_eng.sites (id) ON DELETE SET NULL,
  entity_type text NOT NULL,
  entity_id integer NOT NULL,
  action_name text NOT NULL,
  actor_user_id integer,
  signature_meaning text,
  record_hash text,
  detail_json jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS audit_log_entity_idx
  ON fac_audit.audit_log (entity_type, entity_id, created_at DESC);

ALTER TABLE fac_prod.traveler_steps
  ADD COLUMN IF NOT EXISTS started_at timestamptz,
  ADD COLUMN IF NOT EXISTS signer_user_id integer,
  ADD COLUMN IF NOT EXISTS signature_meaning text,
  ADD COLUMN IF NOT EXISTS record_hash text;

CREATE OR REPLACE VIEW fac_prod.v_traveler_step AS
SELECT
  ts.id AS traveler_step_id,
  t.work_order_id,
  ts.traveler_id,
  ts.routing_operation_id,
  ts.seq,
  ts.operation_code,
  ts.status,
  ts.operator_user_id,
  ts.machine,
  ts.qty_good,
  ts.qty_scrap,
  ts.signed_at,
  ts.started_at,
  ts.signer_user_id,
  ts.signature_meaning,
  ts.record_hash,
  wo.site_id
FROM fac_prod.traveler_steps ts
JOIN fac_prod.travelers t ON t.id = ts.traveler_id
JOIN fac_prod.work_orders wo ON wo.id = t.work_order_id;

ALTER TABLE fac_audit.audit_log ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS audit_log_site ON fac_audit.audit_log;
CREATE POLICY audit_log_site ON fac_audit.audit_log
  FOR ALL
  USING (
    site_id IS NULL
    OR fac_eng.fn_user_can_access_site(
      NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
      site_id
    )
  );

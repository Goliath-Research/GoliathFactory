-- GoliathFactory Phase 3 — first article inspection (AS9102-oriented)
SET client_min_messages = warning;

CREATE TABLE IF NOT EXISTS fac_qual.first_article_reports (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id integer NOT NULL REFERENCES fac_eng.sites (id) ON DELETE RESTRICT,
  work_order_id integer NOT NULL REFERENCES fac_prod.work_orders (id) ON DELETE RESTRICT,
  part_revision_id integer NOT NULL REFERENCES fac_eng.part_revisions (id) ON DELETE RESTRICT,
  inspection_plan_id integer REFERENCES fac_qual.inspection_plans (id) ON DELETE SET NULL,
  status text NOT NULL DEFAULT 'in_progress',
  as9102_form_ref text,
  qa_approved_at timestamptz,
  qa_approver_user_id integer,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (work_order_id)
);

CREATE OR REPLACE VIEW fac_qual.v_first_article AS
SELECT
  f.id AS first_article_id,
  f.site_id,
  f.work_order_id,
  wo.status AS work_order_status,
  f.part_revision_id,
  p.part_number,
  pr.revision AS part_revision,
  f.inspection_plan_id,
  f.status,
  f.as9102_form_ref,
  f.qa_approved_at,
  f.created_at,
  (
    SELECT count(*)::integer
    FROM fac_qual.inspection_results ir
    JOIN fac_qual.inspection_characteristics ic ON ic.id = ir.characteristic_id
    WHERE ic.inspection_plan_id = f.inspection_plan_id
      AND ir.work_order_id = f.work_order_id
  ) AS result_count
FROM fac_qual.first_article_reports f
JOIN fac_prod.work_orders wo ON wo.id = f.work_order_id
JOIN fac_eng.part_revisions pr ON pr.id = f.part_revision_id
JOIN fac_eng.parts p ON p.id = pr.part_id;

ALTER TABLE fac_qual.first_article_reports ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS first_article_reports_site ON fac_qual.first_article_reports;
CREATE POLICY first_article_reports_site ON fac_qual.first_article_reports
  FOR ALL
  USING (
    fac_eng.fn_user_can_access_site(
      NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
      site_id
    )
  );

-- GoliathFactory Phase 1 — fac_prod (work orders, travelers, traveler steps)
SET client_min_messages = warning;

CREATE SCHEMA IF NOT EXISTS fac_prod;

CREATE TABLE IF NOT EXISTS fac_prod.work_orders (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id integer NOT NULL REFERENCES fac_eng.sites (id) ON DELETE RESTRICT,
  part_revision_id integer NOT NULL REFERENCES fac_eng.part_revisions (id) ON DELETE RESTRICT,
  routing_id integer REFERENCES fac_eng.routings (id) ON DELETE RESTRICT,
  quantity numeric(18, 4) NOT NULL,
  output_lot_id integer,
  due_date date,
  status text NOT NULL DEFAULT 'planned',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS fac_prod.travelers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  work_order_id integer NOT NULL REFERENCES fac_prod.work_orders (id) ON DELETE CASCADE,
  UNIQUE (work_order_id)
);

CREATE TABLE IF NOT EXISTS fac_prod.traveler_steps (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  traveler_id integer NOT NULL REFERENCES fac_prod.travelers (id) ON DELETE CASCADE,
  routing_operation_id integer REFERENCES fac_eng.routing_operations (id),
  seq integer NOT NULL,
  operation_code text NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  operator_user_id integer,
  machine text,
  qty_good numeric(18, 4),
  qty_scrap numeric(18, 4),
  signed_at timestamptz,
  UNIQUE (traveler_id, seq)
);

CREATE OR REPLACE VIEW fac_prod.v_work_order AS
SELECT
  wo.id AS work_order_id,
  wo.site_id,
  p.part_number,
  pr.revision AS part_revision,
  wo.part_revision_id,
  wo.routing_id,
  wo.quantity,
  wo.output_lot_id,
  wo.due_date,
  wo.status
FROM fac_prod.work_orders wo
JOIN fac_eng.part_revisions pr ON pr.id = wo.part_revision_id
JOIN fac_eng.parts p ON p.id = pr.part_id;

CREATE OR REPLACE VIEW fac_prod.v_traveler_step AS
SELECT
  ts.id AS traveler_step_id,
  t.work_order_id,
  ts.traveler_id,
  ts.routing_operation_id,
  ts.seq,
  ts.operation_code,
  ts.status,
  ts.operator_user_id,
  ts.machine,
  ts.qty_good,
  ts.qty_scrap,
  ts.signed_at,
  wo.site_id
FROM fac_prod.traveler_steps ts
JOIN fac_prod.travelers t ON t.id = ts.traveler_id
JOIN fac_prod.work_orders wo ON wo.id = t.work_order_id;

ALTER TABLE fac_prod.work_orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE fac_prod.travelers ENABLE ROW LEVEL SECURITY;
ALTER TABLE fac_prod.traveler_steps ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS work_orders_site ON fac_prod.work_orders;
CREATE POLICY work_orders_site ON fac_prod.work_orders
  FOR ALL
  USING (
    fac_eng.fn_user_can_access_site(
      NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
      site_id
    )
  );

DROP POLICY IF EXISTS travelers_site ON fac_prod.travelers;
CREATE POLICY travelers_site ON fac_prod.travelers
  FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM fac_prod.work_orders wo
      WHERE wo.id = work_order_id
        AND fac_eng.fn_user_can_access_site(
          NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
          wo.site_id
        )
    )
  );

DROP POLICY IF EXISTS traveler_steps_site ON fac_prod.traveler_steps;
CREATE POLICY traveler_steps_site ON fac_prod.traveler_steps
  FOR ALL
  USING (
    EXISTS (
      SELECT 1
      FROM fac_prod.travelers tr
      JOIN fac_prod.work_orders wo ON wo.id = tr.work_order_id
      WHERE tr.id = traveler_id
        AND fac_eng.fn_user_can_access_site(
          NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
          wo.site_id
        )
    )
  );

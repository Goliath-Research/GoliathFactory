-- GoliathFactory Phase 1 — fac_eng (parts, revisions, routings, work centers)
SET client_min_messages = warning;

CREATE SCHEMA IF NOT EXISTS fac_eng;

CREATE TABLE IF NOT EXISTS fac_eng.sites (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id integer NOT NULL,
  code text NOT NULL,
  name text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT sites_organization_fk
    FOREIGN KEY (organization_id) REFERENCES portal."Organizations" ("ID"),
  UNIQUE (organization_id, code)
);

CREATE TABLE IF NOT EXISTS fac_eng.parts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id integer NOT NULL,
  part_number text NOT NULL,
  description text,
  CONSTRAINT parts_organization_fk
    FOREIGN KEY (organization_id) REFERENCES portal."Organizations" ("ID"),
  UNIQUE (organization_id, part_number)
);

CREATE TABLE IF NOT EXISTS fac_eng.part_revisions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  part_id integer NOT NULL REFERENCES fac_eng.parts (id) ON DELETE CASCADE,
  revision text NOT NULL,
  material_spec text,
  customer text,
  effectivity_start date,
  effectivity_end date,
  UNIQUE (part_id, revision)
);

CREATE TABLE IF NOT EXISTS fac_eng.work_centers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id integer NOT NULL REFERENCES fac_eng.sites (id) ON DELETE CASCADE,
  code text NOT NULL,
  name text NOT NULL,
  UNIQUE (site_id, code)
);

CREATE TABLE IF NOT EXISTS fac_eng.routings (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  part_revision_id integer NOT NULL REFERENCES fac_eng.part_revisions (id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'draft',
  revision_label text NOT NULL DEFAULT 'A',
  UNIQUE (part_revision_id, revision_label)
);

CREATE TABLE IF NOT EXISTS fac_eng.routing_operations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  routing_id integer NOT NULL REFERENCES fac_eng.routings (id) ON DELETE CASCADE,
  seq integer NOT NULL,
  operation_code text NOT NULL,
  description text,
  work_center_id integer REFERENCES fac_eng.work_centers (id),
  UNIQUE (routing_id, seq)
);

CREATE OR REPLACE FUNCTION fac_eng.fn_user_can_access_site(p_user_id integer, p_site_id integer)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = fac_eng, portal, pg_temp
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM fac_eng.sites s
    WHERE s.id = p_site_id
      AND s.organization_id = ANY (portal.fn_semantic_user_organization_ids(p_user_id))
  );
$$;

CREATE OR REPLACE VIEW fac_eng.v_part_revision AS
SELECT
  pr.id AS part_revision_id,
  p.organization_id,
  p.part_number,
  pr.revision,
  pr.material_spec,
  pr.customer,
  pr.effectivity_start,
  pr.effectivity_end
FROM fac_eng.part_revisions pr
JOIN fac_eng.parts p ON p.id = pr.part_id;

CREATE OR REPLACE VIEW fac_eng.v_routing AS
SELECT
  r.id AS routing_id,
  r.part_revision_id,
  p.part_number,
  pr.revision AS part_revision,
  r.status,
  r.revision_label,
  ro.id AS routing_operation_id,
  ro.seq,
  ro.operation_code,
  ro.description,
  ro.work_center_id,
  wc.code AS work_center_code,
  wc.site_id
FROM fac_eng.routings r
JOIN fac_eng.part_revisions pr ON pr.id = r.part_revision_id
JOIN fac_eng.parts p ON p.id = pr.part_id
LEFT JOIN fac_eng.routing_operations ro ON ro.routing_id = r.id
LEFT JOIN fac_eng.work_centers wc ON wc.id = ro.work_center_id;

ALTER TABLE fac_eng.sites ENABLE ROW LEVEL SECURITY;
ALTER TABLE fac_eng.parts ENABLE ROW LEVEL SECURITY;
ALTER TABLE fac_eng.part_revisions ENABLE ROW LEVEL SECURITY;
ALTER TABLE fac_eng.work_centers ENABLE ROW LEVEL SECURITY;
ALTER TABLE fac_eng.routings ENABLE ROW LEVEL SECURITY;
ALTER TABLE fac_eng.routing_operations ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS sites_org ON fac_eng.sites;
CREATE POLICY sites_org ON fac_eng.sites
  FOR ALL
  USING (
    organization_id = ANY (
      portal.fn_semantic_user_organization_ids(
        NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer
      )
    )
  );

DROP POLICY IF EXISTS parts_org ON fac_eng.parts;
CREATE POLICY parts_org ON fac_eng.parts
  FOR ALL
  USING (
    organization_id = ANY (
      portal.fn_semantic_user_organization_ids(
        NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer
      )
    )
  );

DROP POLICY IF EXISTS part_revisions_org ON fac_eng.part_revisions;
CREATE POLICY part_revisions_org ON fac_eng.part_revisions
  FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM fac_eng.parts p
      WHERE p.id = part_id
        AND p.organization_id = ANY (
          portal.fn_semantic_user_organization_ids(
            NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer
          )
        )
    )
  );

DROP POLICY IF EXISTS work_centers_site ON fac_eng.work_centers;
CREATE POLICY work_centers_site ON fac_eng.work_centers
  FOR ALL
  USING (
    fac_eng.fn_user_can_access_site(
      NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
      site_id
    )
  );

DROP POLICY IF EXISTS routings_org ON fac_eng.routings;
CREATE POLICY routings_org ON fac_eng.routings
  FOR ALL
  USING (
    EXISTS (
      SELECT 1
      FROM fac_eng.part_revisions pr
      JOIN fac_eng.parts p ON p.id = pr.part_id
      WHERE pr.id = part_revision_id
        AND p.organization_id = ANY (
          portal.fn_semantic_user_organization_ids(
            NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer
          )
        )
    )
  );

DROP POLICY IF EXISTS routing_operations_org ON fac_eng.routing_operations;
CREATE POLICY routing_operations_org ON fac_eng.routing_operations
  FOR ALL
  USING (
    EXISTS (
      SELECT 1
      FROM fac_eng.routings r
      JOIN fac_eng.part_revisions pr ON pr.id = r.part_revision_id
      JOIN fac_eng.parts p ON p.id = pr.part_id
      WHERE r.id = routing_id
        AND p.organization_id = ANY (
          portal.fn_semantic_user_organization_ids(
            NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer
          )
        )
    )
  );

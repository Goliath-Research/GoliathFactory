-- GoliathFactory Phase 2 — fac_qual (inspection plans, results, NCR)
SET client_min_messages = warning;

CREATE SCHEMA IF NOT EXISTS fac_qual;

CREATE TABLE IF NOT EXISTS fac_qual.inspection_plans (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id integer NOT NULL REFERENCES fac_eng.sites (id) ON DELETE RESTRICT,
  part_revision_id integer NOT NULL REFERENCES fac_eng.part_revisions (id) ON DELETE RESTRICT,
  name text NOT NULL,
  status text NOT NULL DEFAULT 'active',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS fac_qual.inspection_characteristics (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inspection_plan_id integer NOT NULL REFERENCES fac_qual.inspection_plans (id) ON DELETE CASCADE,
  seq integer NOT NULL,
  characteristic_code text NOT NULL,
  description text,
  nominal numeric(18, 6),
  tolerance_plus numeric(18, 6),
  tolerance_minus numeric(18, 6),
  unit text,
  UNIQUE (inspection_plan_id, seq),
  UNIQUE (inspection_plan_id, characteristic_code)
);

CREATE TABLE IF NOT EXISTS fac_qual.inspection_results (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  characteristic_id integer NOT NULL REFERENCES fac_qual.inspection_characteristics (id) ON DELETE RESTRICT,
  lot_id integer REFERENCES fac_trace.lots (id) ON DELETE SET NULL,
  work_order_id integer REFERENCES fac_prod.work_orders (id) ON DELETE SET NULL,
  piece_number integer NOT NULL DEFAULT 1,
  measured_value numeric(18, 6),
  pass_fail text NOT NULL,
  inspector_user_id integer,
  gauge_id integer,
  recorded_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS fac_qual.ncrs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id integer NOT NULL REFERENCES fac_eng.sites (id) ON DELETE RESTRICT,
  part_revision_id integer REFERENCES fac_eng.part_revisions (id) ON DELETE SET NULL,
  lot_id integer REFERENCES fac_trace.lots (id) ON DELETE SET NULL,
  work_order_id integer REFERENCES fac_prod.work_orders (id) ON DELETE SET NULL,
  defect_code text NOT NULL,
  description text NOT NULL,
  containment text,
  status text NOT NULL DEFAULT 'open',
  opened_by_user_id integer,
  opened_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS fac_qual.mrb_dispositions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ncr_id integer NOT NULL REFERENCES fac_qual.ncrs (id) ON DELETE CASCADE,
  disposition text NOT NULL,
  disposition_at timestamptz NOT NULL DEFAULT now(),
  signer_user_id integer,
  signature_meaning text NOT NULL,
  record_hash text NOT NULL,
  UNIQUE (ncr_id)
);

CREATE OR REPLACE VIEW fac_qual.v_inspection_plan AS
SELECT
  ip.id AS inspection_plan_id,
  ip.site_id,
  ip.part_revision_id,
  p.part_number,
  pr.revision AS part_revision,
  ip.name,
  ip.status,
  ic.id AS characteristic_id,
  ic.seq,
  ic.characteristic_code,
  ic.description,
  ic.nominal,
  ic.tolerance_plus,
  ic.tolerance_minus,
  ic.unit
FROM fac_qual.inspection_plans ip
JOIN fac_eng.part_revisions pr ON pr.id = ip.part_revision_id
JOIN fac_eng.parts p ON p.id = pr.part_id
LEFT JOIN fac_qual.inspection_characteristics ic ON ic.inspection_plan_id = ip.id;

CREATE OR REPLACE VIEW fac_qual.v_inspection_result AS
SELECT
  ir.id AS inspection_result_id,
  ir.characteristic_id,
  ic.characteristic_code,
  ic.description AS characteristic_description,
  ic.inspection_plan_id,
  ip.site_id,
  ip.part_revision_id,
  ir.lot_id,
  l.lot_number,
  ir.work_order_id,
  ir.piece_number,
  ir.measured_value,
  ir.pass_fail,
  ir.inspector_user_id,
  ir.gauge_id,
  ir.recorded_at
FROM fac_qual.inspection_results ir
JOIN fac_qual.inspection_characteristics ic ON ic.id = ir.characteristic_id
JOIN fac_qual.inspection_plans ip ON ip.id = ic.inspection_plan_id
LEFT JOIN fac_trace.lots l ON l.id = ir.lot_id;

CREATE OR REPLACE VIEW fac_qual.v_ncr AS
SELECT
  n.id AS ncr_id,
  n.site_id,
  n.part_revision_id,
  n.lot_id,
  l.lot_number,
  n.work_order_id,
  n.defect_code,
  n.description,
  n.containment,
  n.status,
  n.opened_by_user_id,
  n.opened_at,
  d.disposition,
  d.disposition_at,
  d.signer_user_id,
  d.signature_meaning,
  d.record_hash
FROM fac_qual.ncrs n
LEFT JOIN fac_trace.lots l ON l.id = n.lot_id
LEFT JOIN fac_qual.mrb_dispositions d ON d.ncr_id = n.id;

ALTER TABLE fac_qual.inspection_plans ENABLE ROW LEVEL SECURITY;
ALTER TABLE fac_qual.inspection_characteristics ENABLE ROW LEVEL SECURITY;
ALTER TABLE fac_qual.inspection_results ENABLE ROW LEVEL SECURITY;
ALTER TABLE fac_qual.ncrs ENABLE ROW LEVEL SECURITY;
ALTER TABLE fac_qual.mrb_dispositions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS inspection_plans_site ON fac_qual.inspection_plans;
CREATE POLICY inspection_plans_site ON fac_qual.inspection_plans
  FOR ALL
  USING (
    fac_eng.fn_user_can_access_site(
      NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
      site_id
    )
  );

DROP POLICY IF EXISTS inspection_characteristics_site ON fac_qual.inspection_characteristics;
CREATE POLICY inspection_characteristics_site ON fac_qual.inspection_characteristics
  FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM fac_qual.inspection_plans ip
      WHERE ip.id = inspection_plan_id
        AND fac_eng.fn_user_can_access_site(
          NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
          ip.site_id
        )
    )
  );

DROP POLICY IF EXISTS inspection_results_site ON fac_qual.inspection_results;
CREATE POLICY inspection_results_site ON fac_qual.inspection_results
  FOR ALL
  USING (
    EXISTS (
      SELECT 1
      FROM fac_qual.inspection_characteristics ic
      JOIN fac_qual.inspection_plans ip ON ip.id = ic.inspection_plan_id
      WHERE ic.id = characteristic_id
        AND fac_eng.fn_user_can_access_site(
          NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
          ip.site_id
        )
    )
  );

DROP POLICY IF EXISTS ncrs_site ON fac_qual.ncrs;
CREATE POLICY ncrs_site ON fac_qual.ncrs
  FOR ALL
  USING (
    fac_eng.fn_user_can_access_site(
      NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
      site_id
    )
  );

DROP POLICY IF EXISTS mrb_dispositions_site ON fac_qual.mrb_dispositions;
CREATE POLICY mrb_dispositions_site ON fac_qual.mrb_dispositions
  FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM fac_qual.ncrs n
      WHERE n.id = ncr_id
        AND fac_eng.fn_user_can_access_site(
          NULLIF(current_setting('goliath.mfg.user_id', true), '')::integer,
          n.site_id
        )
    )
  );
